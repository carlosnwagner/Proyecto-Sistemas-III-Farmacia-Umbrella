-- Esquema aislado que reproduce las columnas y triggers diagnosticados.
create role anon;
create role authenticated;
create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table usuario(id_usuario integer primary key,estado boolean);
create table sucursal(id_sucursal integer primary key);
create table medio_pago(id_medio_pago integer primary key,nombre text,estado boolean);
create table caja(id bigint generated by default as identity primary key,sucursal_id bigint,nombre text,activa boolean);
create table turno_caja(id bigint generated by default as identity primary key,caja_id bigint,sucursal_id bigint,cajero_id bigint,fecha_hora_apertura timestamptz default now(),saldo_inicial numeric,estado text default 'Abierto');
create unique index uq_turno_abierto_por_caja on turno_caja(caja_id) where estado='Abierto';
create table arqueo_caja(id_arqueo bigint generated always as identity primary key,turno_id bigint,usuario_id integer,efectivo_esperado numeric,efectivo_contado numeric,diferencia numeric,fecha_hora timestamptz default now(),valido_para_cierre boolean default true);
create function validar_turno_caja_abierto() returns trigger language plpgsql as $$begin return new; end;$$;
create trigger trg_arqueo_caja_turno_abierto before insert or update on arqueo_caja for each row execute function validar_turno_caja_abierto();
