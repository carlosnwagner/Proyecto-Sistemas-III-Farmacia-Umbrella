-- HU66: registrar solicitudes de retiro sin crear ventas, cobros ni movimientos de stock.
begin;

create table if not exists public.pedido_online (
  id_pedido bigint generated by default as identity primary key,
  referencia uuid not null default gen_random_uuid() unique,
  id_sucursal integer not null references public.sucursal(id_sucursal),
  nombre_cliente text not null,
  apellido_cliente text not null,
  contacto text not null,
  importe_estimado numeric(14,2) not null default 0,
  estado text not null default 'Pendiente',
  fecha_creacion timestamptz not null default now(),
  fecha_actualizacion timestamptz not null default now(),
  motivo_cancelacion text,
  constraint pedido_online_estado_check check (estado in ('Pendiente','Preparado','Cancelado','Entregado')),
  constraint pedido_online_motivo_cancelacion_check check ((estado='Cancelado' and nullif(btrim(motivo_cancelacion),'') is not null) or (estado<>'Cancelado' and motivo_cancelacion is null)),
  constraint pedido_online_importe_check check (importe_estimado >= 0),
  constraint pedido_online_nombre_check check (length(btrim(nombre_cliente)) > 0 and length(btrim(apellido_cliente)) > 0 and length(btrim(contacto)) > 0)
);

create table if not exists public.detalle_pedido_online (
  id_detalle bigint generated by default as identity primary key,
  id_pedido bigint not null references public.pedido_online(id_pedido) on delete cascade,
  id_articulo integer not null references public.articulo(id_articulo),
  id_articulo_deposito integer not null references public.articulo_deposito(id_articulo_deposito),
  cantidad integer not null check (cantidad > 0),
  precio_unitario numeric(14,2) not null check (precio_unitario > 0),
  subtotal numeric(14,2) generated always as (cantidad * precio_unitario) stored,
  constraint detalle_pedido_online_articulo_unique unique (id_pedido,id_articulo),
  constraint detalle_pedido_online_inventario_unique unique (id_pedido,id_articulo_deposito)
);

create table if not exists public.pedido_online_idempotencia (
  clave uuid primary key,
  id_pedido bigint not null references public.pedido_online(id_pedido) on delete cascade,
  payload jsonb not null
);

revoke all on public.pedido_online, public.detalle_pedido_online, public.pedido_online_idempotencia from public, anon, authenticated;

create or replace function public.registrar_pedido_online(
  p_clave uuid,
  p_id_sucursal integer,
  p_nombre text,
  p_apellido text,
  p_contacto text,
  p_items jsonb
)
returns table (id_pedido bigint, referencia uuid, id_sucursal integer, nombre_cliente text, apellido_cliente text, contacto text, importe_estimado numeric, estado text, fecha_creacion timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pedido public.pedido_online%rowtype;
  v_item jsonb;
  v_id_articulo integer;
  v_cantidad integer;
  v_precio numeric(14,2);
  v_precio_actual numeric(14,2);
  v_precio_esperado numeric(14,2);
  v_id_articulo_deposito integer;
  v_total numeric(14,2) := 0;
  v_detalles jsonb := '[]'::jsonb;
  v_payload jsonb;
begin
  if p_clave is null then raise exception 'Clave de solicitud inválida'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_clave::text, 0));
  v_payload := jsonb_build_object(
    'id_sucursal', p_id_sucursal,
    'nombre', btrim(coalesce(p_nombre,'')),
    'apellido', btrim(coalesce(p_apellido,'')),
    'contacto', btrim(coalesce(p_contacto,'')),
    'items', coalesce((select jsonb_agg(jsonb_build_object('id_articulo',(x->>'id_articulo')::integer,'cantidad',(x->>'cantidad')::integer) order by (x->>'id_articulo')::integer) from jsonb_array_elements(coalesce(p_items,'[]'::jsonb)) x), '[]'::jsonb)
  );
  select po.* into v_pedido from public.pedido_online_idempotencia i
  join public.pedido_online po using (id_pedido) where i.clave = p_clave;
  if found then
    if (select i.payload from public.pedido_online_idempotencia i where i.clave=p_clave) is distinct from v_payload then
      raise exception 'La clave ya fue usada con otros datos. Recuperá el pedido anterior antes de iniciar uno nuevo';
    end if;
    return query select v_pedido.id_pedido,v_pedido.referencia,v_pedido.id_sucursal,v_pedido.nombre_cliente,v_pedido.apellido_cliente,v_pedido.contacto,v_pedido.importe_estimado,v_pedido.estado,v_pedido.fecha_creacion; return;
  end if;

  if not public.catalogo_sucursal_valida(p_id_sucursal) then raise exception 'La sucursal seleccionada no está disponible'; end if;
  if nullif(btrim(p_nombre),'') is null or nullif(btrim(p_apellido),'') is null or nullif(btrim(p_contacto),'') is null then raise exception 'Completá nombre, apellido y contacto'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'El pedido no tiene productos'; end if;
  if jsonb_array_length(p_items) > 30 then raise exception 'El pedido supera el máximo de 30 productos diferentes'; end if;
  if jsonb_array_length(p_items) <> (select count(distinct (x->>'id_articulo')::integer) from jsonb_array_elements(p_items) x) then raise exception 'Hay productos repetidos en el pedido'; end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_id_articulo := (v_item->>'id_articulo')::integer;
    v_cantidad := (v_item->>'cantidad')::integer;
    v_precio_esperado := (v_item->>'precio_esperado')::numeric;
    if v_cantidad <= 0 or v_cantidad > 100 then raise exception 'La cantidad debe estar entre 1 y 100 unidades'; end if;
    select dlp.precio_final
      into v_precio_actual
    from public.detalle_lista_precio dlp
    join public.lista_precio lp on lp.id_lista = dlp.id_lista
    where dlp.id_articulo = v_id_articulo and lp.estado is true
      and lp.fecha_inicio <= current_date and (lp.fecha_fin is null or lp.fecha_fin >= current_date)
    order by lp.fecha_inicio desc,lp.id_lista desc limit 1;
    if v_precio_actual is null or v_precio_actual <= 0 then raise exception 'El producto % ya no tiene un precio vigente', v_id_articulo; end if;
    if v_precio_esperado is null or round(v_precio_esperado,2) is distinct from round(v_precio_actual,2) then
      raise exception 'El precio del producto % cambió. Quitalo del carrito y volvé a agregarlo para revisar el precio vigente', v_id_articulo;
    end if;
    select ad.id_articulo_deposito into v_id_articulo_deposito
    from public.articulo a
    join public.articulo_deposito ad on ad.id_articulo = a.id_articulo and ad.estado is true and ad.stock_actual >= v_cantidad
    join public.deposito d on d.id_deposito = ad.id_deposito and d.id_sucursal = p_id_sucursal and d.estado is true
    where a.id_articulo = v_id_articulo and a.estado is true and a.publicado_online is true
    order by ad.stock_actual desc, ad.id_articulo_deposito limit 1;
    if v_id_articulo_deposito is null then raise exception 'El producto % ya no está disponible', v_id_articulo; end if;
    v_precio := round(v_precio_actual,2);
    v_total := v_total + v_precio*v_cantidad;
    v_detalles := v_detalles || jsonb_build_array(jsonb_build_object('id_articulo',v_id_articulo,'id_articulo_deposito',v_id_articulo_deposito,'cantidad',v_cantidad,'precio_unitario',v_precio));
  end loop;

  insert into public.pedido_online(id_sucursal,nombre_cliente,apellido_cliente,contacto,importe_estimado)
  values (p_id_sucursal,btrim(p_nombre),btrim(p_apellido),btrim(p_contacto),v_total) returning * into v_pedido;
  insert into public.detalle_pedido_online(id_pedido,id_articulo,id_articulo_deposito,cantidad,precio_unitario)
  select v_pedido.id_pedido,(x->>'id_articulo')::integer,(x->>'id_articulo_deposito')::integer,(x->>'cantidad')::integer,(x->>'precio_unitario')::numeric from jsonb_array_elements(v_detalles) x;
  insert into public.pedido_online_idempotencia(clave,id_pedido,payload) values (p_clave,v_pedido.id_pedido,v_payload);
  return query select v_pedido.id_pedido,v_pedido.referencia,v_pedido.id_sucursal,v_pedido.nombre_cliente,v_pedido.apellido_cliente,v_pedido.contacto,v_pedido.importe_estimado,v_pedido.estado,v_pedido.fecha_creacion;
end;
$$;

revoke all on function public.registrar_pedido_online(uuid,integer,text,text,text,jsonb) from public;
grant execute on function public.registrar_pedido_online(uuid,integer,text,text,text,jsonb) to anon, authenticated;

create or replace function public.hu66_listar_pedidos()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_pedidos jsonb;
begin
  if not exists (select 1 from public.usuario u where u.auth_id=auth.uid() and u.estado is true and u.rol='administrador') then
    raise exception 'No tenés permiso para consultar pedidos online';
  end if;
  select coalesce(jsonb_agg(to_jsonb(p) || jsonb_build_object(
    'sucursal', jsonb_build_object('codigo',s.codigo,'descripcion',s.descripcion),
    'items', coalesce((select jsonb_agg(jsonb_build_object('id_articulo',d.id_articulo,'nombre',a.nombre,'cantidad',d.cantidad,'precio_unitario',d.precio_unitario,'subtotal',d.subtotal) order by a.nombre) from public.detalle_pedido_online d join public.articulo a using(id_articulo) where d.id_pedido=p.id_pedido),'[]'::jsonb)
  ) order by p.fecha_creacion desc), '[]'::jsonb)
  into v_pedidos from public.pedido_online p join public.sucursal s using(id_sucursal);
  return v_pedidos;
end;
$$;

create or replace function public.hu66_actualizar_estado_pedido(p_id_pedido bigint,p_estado text,p_motivo text default null)
returns public.pedido_online
language plpgsql
security definer
set search_path = public
as $$
declare v_pedido public.pedido_online%rowtype;
begin
  if not exists (select 1 from public.usuario u where u.auth_id=auth.uid() and u.estado is true and u.rol='administrador') then
    raise exception 'No tenés permiso para gestionar pedidos online';
  end if;
  if p_estado not in ('Preparado','Cancelado','Entregado') then raise exception 'Estado de pedido inválido'; end if;
  if p_estado='Cancelado' and nullif(btrim(p_motivo),'') is null then raise exception 'Indicá el motivo de cancelación para informar al cliente'; end if;
  update public.pedido_online set estado=p_estado,fecha_actualizacion=now(),motivo_cancelacion=case when p_estado='Cancelado' then btrim(p_motivo) else null end
  where id_pedido=p_id_pedido and estado in ('Pendiente','Preparado') returning * into v_pedido;
  if not found then raise exception 'El pedido no existe o ya no admite cambios'; end if;
  return v_pedido;
end;
$$;

revoke all on function public.hu66_listar_pedidos() from public, anon;
revoke all on function public.hu66_actualizar_estado_pedido(bigint,text,text) from public, anon;
grant execute on function public.hu66_listar_pedidos() to authenticated;
grant execute on function public.hu66_actualizar_estado_pedido(bigint,text,text) to authenticated;

create or replace function public.hu66_consultar_estado_pedido(p_referencia uuid)
returns table (id_pedido bigint, estado text, sucursal_codigo text, sucursal_descripcion text, fecha_creacion timestamptz, fecha_actualizacion timestamptz, importe_estimado numeric, motivo_cancelacion text, items jsonb)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if p_referencia is null then return; end if;
  return query
  select p.id_pedido,p.estado,s.codigo::text,s.descripcion::text,p.fecha_creacion,p.fecha_actualizacion,p.importe_estimado,p.motivo_cancelacion,
    coalesce((select jsonb_agg(jsonb_build_object('nombre',a.nombre,'cantidad',d.cantidad,'precio_unitario',d.precio_unitario,'subtotal',d.subtotal) order by a.nombre)
      from public.detalle_pedido_online d join public.articulo a using(id_articulo) where d.id_pedido=p.id_pedido),'[]'::jsonb)
  from public.pedido_online p join public.sucursal s using (id_sucursal)
  where p.referencia=p_referencia;
end;
$$;

revoke all on function public.hu66_consultar_estado_pedido(uuid) from public;
grant execute on function public.hu66_consultar_estado_pedido(uuid) to anon, authenticated;
comment on table public.pedido_online is 'Solicitudes online de retiro. No son ventas, no reservan stock y no generan cobros.';
commit;
