  and a.precio_venta > 0
on conflict (id_lista_precio, id_articulo) do nothing;

-- Devuelve el precio aplicable o ninguna fila cuando el articulo no tiene precio vigente.
create or replace function public.obtener_precio_vigente(
  p_id_articulo integer,
  p_fecha_venta date default current_date
)
returns table (
  id_lista_precio bigint,
  nombre_lista text,
  precio_base numeric,
  tipo_ajuste text,
  valor_ajuste numeric,
  precio_final numeric
)
language sql
stable
as $$
  select
    lp.id_lista_precio,
    lp.nombre,
    dlp.precio_base,
    dlp.tipo_ajuste,
    dlp.valor_ajuste,
    dlp.precio_final
  from public.lista_precio lp
  join public.detalle_lista_precio dlp
    on dlp.id_lista_precio = lp.id_lista_precio
  where dlp.id_articulo = p_id_articulo
    and lp.estado = 'Activa'
    and lp.fecha_desde <= p_fecha_venta
    and (lp.fecha_hasta is null or lp.fecha_hasta >= p_fecha_venta)
  order by lp.fecha_desde desc
  limit 1;
$$;
